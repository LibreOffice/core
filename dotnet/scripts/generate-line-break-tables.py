"""Generate the Unicode properties the line breaker needs, as sorted range tables.

Line_Break and Extended_Pictographic come from the `uniseg` package's compiled property
tables; East_Asian_Width and the general category come from Python's own unicodedata. Both
are derived from the Unicode Character Database — this script exists so the tables are
regenerable rather than hand-maintained, and so the source of each one is recorded.

Ranges rather than a two-stage trie: the property is heavily run-length structured (a few
thousand ranges over 1.1 million code points), so a sorted range array with a binary search
is both smaller than a trie and legible in a diff.
"""
import sys
import unicodedata

import uniseg.linebreak as lb
import uniseg.db as db

MAX = 0x110000

# The classes UAX #14 defines, in the order the C# enum declares them.
CLASSES = [
    'XX', 'AI', 'AL', 'B2', 'BA', 'BB', 'BK', 'CB', 'CJ', 'CL', 'CM', 'CP', 'CR',
    'EB', 'EM', 'EX', 'GL', 'H2', 'H3', 'HL', 'HY', 'ID', 'IN', 'IS', 'JL', 'JT',
    'JV', 'LF', 'NL', 'NS', 'NU', 'OP', 'PO', 'PR', 'QU', 'RI', 'SA', 'SG', 'SP',
    'SY', 'WJ', 'ZW', 'ZWJ', 'AK', 'AP', 'AS', 'VF', 'VI',
]

handle_lb = db.get_handle('Line_Break')
handle_pict = db.get_handle('Extended_Pictographic')


def line_break_of(cp):
    value = db.get_value(handle_lb, cp)
    return value if value else 'XX'


def extended_pictographic(cp):
    return db.get_value(handle_pict, cp) == 'Y'


def ranges(value_of, default=None):
    """Sorted (start, end, value) ranges, omitting runs equal to `default`."""
    out = []
    start = 0
    current = value_of(0)
    for cp in range(1, MAX):
        value = value_of(cp)
        if value != current:
            if current != default:
                out.append((start, cp - 1, current))
            start = cp
            current = value
    if current != default:
        out.append((start, MAX - 1, current))
    return out


print('reading Line_Break…', file=sys.stderr)
lb_ranges = ranges(line_break_of, default='XX')

print('reading Extended_Pictographic…', file=sys.stderr)
pict_ranges = [(a, b) for a, b, v in ranges(extended_pictographic, default=False)]

print('reading East_Asian_Width…', file=sys.stderr)


def wide(cp):
    try:
        return unicodedata.east_asian_width(chr(cp)) in ('F', 'W', 'H')
    except ValueError:
        return False


wide_ranges = [(a, b) for a, b, v in ranges(wide, default=False)]

print(f'{len(lb_ranges)} line-break ranges, {len(pict_ranges)} pictographic, '
      f'{len(wide_ranges)} wide', file=sys.stderr)

unknown = sorted({v for _, _, v in lb_ranges} - set(CLASSES))
if unknown:
    print('UNKNOWN CLASSES:', unknown, file=sys.stderr)
    sys.exit(1)

out = []
w = out.append
w('// <auto-generated>')
w('// Unicode properties the line breaker needs, as sorted ranges.')
w('//')
w('//   Line_Break, Extended_Pictographic   from the uniseg package\'s property tables')
w('//   East_Asian_Width                    from Python\'s unicodedata')
w('//')
w('// Both derive from the Unicode Character Database. Regenerate rather than edit: this is data,')
w('// and a hand-made correction to one range would be lost the next time it is rebuilt. The')
w('// generator is scripts/generate-line-break-tables.py and it can read the UCD directly when')
w('// unicode.org is reachable.')
w('// </auto-generated>')
w('')
w('namespace Paperless.Text.Layout;')
w('')
w('public static partial class LineBreakProperties')
w('{')
w('    /// <summary>The first code point of each run, ascending; searched by bisection.</summary>')
w('    private static readonly int[] ClassStarts =')
w('    [')
for i in range(0, len(lb_ranges), 12):
    chunk = lb_ranges[i:i + 12]
    w('        ' + ' '.join(f'0x{a:X},' for a, _, _ in chunk))
w('    ];')
w('')
w('    /// <summary>One past the last code point of each run, in the same order.</summary>')
w('    private static readonly int[] ClassEnds =')
w('    [')
for i in range(0, len(lb_ranges), 12):
    chunk = lb_ranges[i:i + 12]
    w('        ' + ' '.join(f'0x{b + 1:X},' for _, b, _ in chunk))
w('    ];')
w('')
w('    /// <summary>The class of each run, in the same order.</summary>')
w('    private static readonly LineBreakClass[] Classes =')
w('    [')
for i in range(0, len(lb_ranges), 16):
    chunk = lb_ranges[i:i + 16]
    w('        ' + ' '.join(f'LineBreakClass.{v},' for _, _, v in chunk))
w('    ];')
w('')


def emit_pairs(name, summary, pairs):
    w(f'    /// <summary>{summary}</summary>')
    w(f'    private static readonly int[] {name} =')
    w('    [')
    for i in range(0, len(pairs), 8):
        chunk = pairs[i:i + 8]
        w('        ' + ' '.join(f'0x{a:X}, 0x{b + 1:X},' for a, b in chunk))
    w('    ];')
    w('')


emit_pairs('PictographicRanges',
           'Extended_Pictographic ranges as start and end pairs, ascending.',
           pict_ranges)
emit_pairs('WideRanges',
           'East_Asian_Width F, W and H ranges as start and end pairs, ascending.',
           wide_ranges)
w('}')

path = ('/home/user/libreoffice-core/dotnet/src/Paperless.Text/Layout/'
        'LineBreakProperties.Tables.cs')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('written ' + path, file=sys.stderr)
