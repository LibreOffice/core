"""Generate the Unicode properties the itemiser needs, as sorted range tables.

Two files come out of this: the bidi properties (`Bidi_Class`, `Bidi_Paired_Bracket_Type`
and `Bidi_Paired_Bracket`) and the script property (UAX #24 `Script`, as ISO 15924 codes).

The source is **ICU**, read through `ctypes` from the system's `libicuuc`. That is a
deliberate choice rather than a convenience: LibreOffice resolves bidi with `ubidi_setPara`
and itemises scripts with `uscript_getScript` (`vcl/source/text/ImplLayoutArgs.cxx`,
`vcl/source/gdi/scrptrun.cxx`), so ICU's tables *are* the authority for agreeing with it.
The line-break tables in this directory come from a Python package that embeds the UCD
because no equivalent authority exists for UAX #14; here one does.

The Unicode version is whatever the installed ICU carries, and it is written into the
generated file so a regeneration that moves it is visible in the diff.

Ranges rather than a trie, for the same reason as the line-break tables: the properties are
heavily run-length structured, so a sorted range array with a binary search is smaller than
a trie and legible in a diff.
"""
import ctypes
import ctypes.util
import sys

MAX = 0x110000

# ICU exports versioned symbols: u_charDirection_74 and so on. The suffix is discovered
# rather than assumed, because a container upgrade changes it.
CANDIDATE_LIBRARIES = ['libicuuc.so.74', 'libicuuc.so', 'libicuuc.so.72', 'libicuuc.so.76']

# u_getIntPropertyValue selectors, from unicode/uchar.h.
UCHAR_GENERAL_CATEGORY = 0x1005
UCHAR_BIDI_PAIRED_BRACKET_TYPE = 0x1015

# UCharDirection, in declaration order — this is the order the C# enum declares too, so the
# integer ICU returns is the enum member.
DIRECTIONS = [
    'L', 'R', 'EN', 'ES', 'ET', 'AN', 'CS', 'B', 'S', 'WS', 'ON',
    'LRE', 'LRO', 'AL', 'RLE', 'RLO', 'PDF', 'NSM', 'BN',
    'FSI', 'LRI', 'RLI', 'PDI',
]

# UCharCategory
U_NON_SPACING_MARK = 6


def load_icu():
    for name in CANDIDATE_LIBRARIES:
        try:
            library = ctypes.CDLL(name)
        except OSError:
            continue
        for suffix in [''] + [f'_{v}' for v in range(60, 90)]:
            if hasattr(library, 'u_charDirection' + suffix):
                return library, suffix
    print('no libicuuc found; this script needs the ICU LibreOffice itself uses',
          file=sys.stderr)
    sys.exit(1)


icu, SUFFIX = load_icu()


def fn(name, restype, argtypes):
    f = getattr(icu, name + SUFFIX)
    f.restype = restype
    f.argtypes = argtypes
    return f


u_charDirection = fn('u_charDirection', ctypes.c_int, [ctypes.c_int32])
u_getBidiPairedBracket = fn('u_getBidiPairedBracket', ctypes.c_int32, [ctypes.c_int32])
u_getIntPropertyValue = fn(
    'u_getIntPropertyValue', ctypes.c_int32, [ctypes.c_int32, ctypes.c_int])
uscript_getScript = fn(
    'uscript_getScript', ctypes.c_int, [ctypes.c_int32, ctypes.POINTER(ctypes.c_int)])
uscript_getShortName = fn('uscript_getShortName', ctypes.c_char_p, [ctypes.c_int])
u_getUnicodeVersion = fn('u_getUnicodeVersion', None, [ctypes.c_char * 4])

_version = (ctypes.c_char * 4)()
u_getUnicodeVersion(_version)
UNICODE_VERSION = '.'.join(str(b) for b in _version.raw[:3])
print(f'ICU carries Unicode {UNICODE_VERSION}', file=sys.stderr)


def ranges(value_of, default=None):
    """Sorted (start, end, value) ranges, omitting runs equal to `default`."""
    out = []
    start = 0
    current = value_of(0)
    for cp in range(1, MAX):
        value = value_of(cp)
        if value != current:
            if current != default:
                out.append((start, cp - 1, current))
            start = cp
            current = value
    if current != default:
        out.append((start, MAX - 1, current))
    return out


def chunked(writer, items, per_line, render):
    for i in range(0, len(items), per_line):
        writer('        ' + ' '.join(render(item) for item in items[i:i + per_line]))


def header(writer, summary):
    writer('// <auto-generated>')
    writer(f'// {summary}')
    writer('//')
    writer(f'// Read from ICU (Unicode {UNICODE_VERSION}) by scripts/generate-itemisation-tables.py.')
    writer('// ICU is what LibreOffice itself resolves bidi and script with, so these tables are the')
    writer('// authority for agreeing with it rather than merely a defensible second opinion.')
    writer('//')
    writer('// Regenerate rather than edit: this is data, and a hand-made correction to one range')
    writer('// would be lost the next time it is rebuilt.')
    writer('// </auto-generated>')
    writer('')


# ---------------------------------------------------------------- bidi properties

print('reading Bidi_Class…', file=sys.stderr)
bidi_ranges = ranges(lambda cp: DIRECTIONS[u_charDirection(cp)], default='L')

print('reading Bidi_Paired_Bracket…', file=sys.stderr)
brackets = []
for cp in range(MAX):
    kind = u_getIntPropertyValue(cp, UCHAR_BIDI_PAIRED_BRACKET_TYPE)
    if kind:
        brackets.append((cp, u_getBidiPairedBracket(cp), kind))

print(f'{len(bidi_ranges)} bidi-class ranges, {len(brackets)} bracket characters',
      file=sys.stderr)

out = []
w = out.append
header(w, 'The Unicode properties the bidirectional algorithm needs, as sorted ranges.')
w('namespace Paperless.Text.Itemisation;')
w('')
w('public static partial class BidiProperties')
w('{')
w('    /// <summary>The Unicode version these tables were read from.</summary>')
w(f'    public const string UnicodeVersion = "{UNICODE_VERSION}";')
w('')
w('    /// <summary>The first code point of each run, ascending; searched by bisection.</summary>')
w('    /// <remarks>Runs of the default class <c>L</c> are omitted, which is most of the plane.</remarks>')
w('    private static readonly int[] ClassStarts =')
w('    [')
chunked(w, bidi_ranges, 12, lambda r: f'0x{r[0]:X},')
w('    ];')
w('')
w('    /// <summary>One past the last code point of each run, in the same order.</summary>')
w('    private static readonly int[] ClassEnds =')
w('    [')
chunked(w, bidi_ranges, 12, lambda r: f'0x{r[1] + 1:X},')
w('    ];')
w('')
w('    /// <summary>The class of each run, in the same order.</summary>')
w('    private static readonly BidiClass[] Classes =')
w('    [')
chunked(w, bidi_ranges, 10, lambda r: f'BidiClass.{r[2]},')
w('    ];')
w('')
w('    /// <summary>Every character with a paired bracket, ascending.</summary>')
w('    private static readonly int[] BracketChars =')
w('    [')
chunked(w, brackets, 10, lambda b: f'0x{b[0]:X},')
w('    ];')
w('')
w('    /// <summary>The bracket each of those pairs with, in the same order.</summary>')
w('    private static readonly int[] BracketPairs =')
w('    [')
chunked(w, brackets, 10, lambda b: f'0x{b[1]:X},')
w('    ];')
w('')
w('    /// <summary>Whether each is an opening or a closing bracket, in the same order.</summary>')
w('    private static readonly BracketType[] BracketTypes =')
w('    [')
chunked(w, brackets, 8,
        lambda b: f'BracketType.{"Open" if b[2] == 1 else "Close"},')
w('    ];')
w('}')

BIDI_PATH = ('/home/user/wt-text-bidi/dotnet/src/Paperless.Text/Itemisation/'
             'BidiProperties.Tables.cs')
open(BIDI_PATH, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('written ' + BIDI_PATH, file=sys.stderr)

# ---------------------------------------------------------------- script property

print('reading Script…', file=sys.stderr)
_error = ctypes.c_int(0)


def script_of(cp):
    # tdf#154549: LibreOffice makes a non-spacing mark inherit its base's script whatever
    # its own says, so that a mark never opens a run of its own. Baking it into the table
    # keeps the itemiser's own code free of a special case it would have to remember.
    if u_getIntPropertyValue(cp, UCHAR_GENERAL_CATEGORY) == U_NON_SPACING_MARK:
        return 'Zinh'
    _error.value = 0
    name = uscript_getShortName(uscript_getScript(cp, ctypes.byref(_error)))
    code = name.decode('ascii') if name else 'Zzzz'
    # There are three script codes for Japanese and one OpenType script tag, so splitting
    # them apart would gain nothing and cost a shaping boundary (`getScript` in
    # vcl/source/gdi/scrptrun.cxx).
    return 'Hira' if code in ('Kana', 'Hrkt') else code


script_ranges = ranges(script_of, default='Zzzz')
codes = sorted({r[2] for r in script_ranges})
index_of = {code: i for i, code in enumerate(codes)}
print(f'{len(script_ranges)} script ranges over {len(codes)} scripts', file=sys.stderr)

out = []
w = out.append
header(w, 'The UAX #24 Script property, as sorted ranges of ISO 15924 codes.')
w('namespace Paperless.Text.Itemisation;')
w('')
w('public static partial class ScriptProperties')
w('{')
w('    /// <summary>The Unicode version these tables were read from.</summary>')
w(f'    public const string UnicodeVersion = "{UNICODE_VERSION}";')
w('')
w('    /// <summary>Every script code appearing in the table, sorted; the tables index into this.</summary>')
w('    private static readonly string[] Codes =')
w('    [')
chunked(w, codes, 8, lambda c: f'"{c}",')
w('    ];')
w('')
w('    /// <summary>The first code point of each run, ascending; searched by bisection.</summary>')
w('    /// <remarks>Runs of <c>Zzzz</c> (Unknown) are omitted, which is every unassigned block.</remarks>')
w('    private static readonly int[] ScriptStarts =')
w('    [')
chunked(w, script_ranges, 12, lambda r: f'0x{r[0]:X},')
w('    ];')
w('')
w('    /// <summary>One past the last code point of each run, in the same order.</summary>')
w('    private static readonly int[] ScriptEnds =')
w('    [')
chunked(w, script_ranges, 12, lambda r: f'0x{r[1] + 1:X},')
w('    ];')
w('')
w('    /// <summary>An index into <c>Codes</c> for each run, in the same order.</summary>')
w('    private static readonly byte[] ScriptIndices =')
w('    [')
chunked(w, script_ranges, 20, lambda r: f'{index_of[r[2]]},')
w('    ];')
w('}')

if len(codes) > 255:
    print('more scripts than a byte index can hold; widen ScriptIndices', file=sys.stderr)
    sys.exit(1)

SCRIPT_PATH = ('/home/user/wt-text-bidi/dotnet/src/Paperless.Text/Itemisation/'
               'ScriptProperties.Tables.cs')
open(SCRIPT_PATH, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('written ' + SCRIPT_PATH, file=sys.stderr)
