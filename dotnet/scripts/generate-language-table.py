"""Generate the LCID -> BCP 47 table from LibreOffice's own isolang tables.

Reads include/i18nlangtag/lang.h for the LANGUAGE_* numeric values and
i18nlangtag/source/isolang/isolang.cxx for the tag each one maps to, then emits a
C# source file. Generated rather than hand-typed because the table is hundreds of
rows of pure data and a typo in it silently mislabels a document's language.

The three tables are consulted in the order MsLangId::Conversion uses -- BCP-47
first, then language+script+country, then language+country -- and an entry whose
mnOverride is set is not canonical, so it is skipped in favour of the entry the
override names.
"""
import re
import sys

ROOT = '/home/user/libreoffice-core/'
HEADER = ROOT + 'include/i18nlangtag/lang.h'
SOURCE = ROOT + 'i18nlangtag/source/isolang/isolang.cxx'

# ---------------------------------------------------------------- lang.h values

names = {}
pending = []
header = open(HEADER, encoding='utf-8').read()
for m in re.finditer(
        r'^#define\s+(LANGUAGE_[A-Z0-9_]+)\s+(?:LanguageType\()?\s*'
        r'(0x[0-9a-fA-F]+|LANGUAGE_[A-Z0-9_]+)\s*\)?',
        header, re.M):
    name, value = m.group(1), m.group(2)
    if value.startswith('0x'):
        names[name] = int(value, 16)
    else:
        pending.append((name, value))

for _ in range(8):
    for name, value in list(pending):
        if value in names:
            names[name] = names[value]
            pending.remove((name, value))
    if not pending:
        break

# ---------------------------------------------------------------- isolang.cxx tables

source = open(SOURCE, encoding='utf-8').read()


def body_of(struct_name):
    start = source.index(struct_name + ' const a')
    open_brace = source.index('{', start)
    depth = 0
    i = open_brace
    while True:
        if source[i] == '{':
            depth += 1
        elif source[i] == '}':
            depth -= 1
            if depth == 0:
                break
        i += 1
    return source[open_brace + 1:i]


ISO_ROW = re.compile(
    r'\{\s*(LANGUAGE_[A-Z0-9_]+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,'
    r'\s*(k0|kSAME|LANGUAGE_[A-Z0-9_]+)\s*\}')

BCP_ROW = re.compile(
    r'\{\s*(LANGUAGE_[A-Z0-9_]+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,'
    r'\s*(?:"([^"]*)"|nullptr)\s*,\s*(k0|kSAME|LANGUAGE_[A-Z0-9_]+)\s*\}')

# Rows in lookup order, as (lcid_name, tag, override_name).
rows = []

for m in BCP_ROW.finditer(body_of('Bcp47CountryEntry')):
    rows.append((m.group(1), m.group(2), m.group(5)))

for m in ISO_ROW.finditer(body_of('IsoLanguageScriptCountryEntry')):
    rows.append((m.group(1), '-'.join(p for p in (m.group(2), m.group(3)) if p), m.group(4)))

for m in ISO_ROW.finditer(body_of('IsoLanguageCountryEntry')):
    rows.append((m.group(1), '-'.join(p for p in (m.group(2), m.group(3)) if p), m.group(4)))

# Pass one: the canonical tag for each LCID -- an entry with no override, first table wins.
canonical = {}
for name, tag, override in rows:
    if override != 'k0' or name not in names or not tag:
        continue
    canonical.setdefault(names[name], tag)

# Pass two: an override naming a different LCID redirects to that LCID's canonical tag.
# kSAME needs nothing: the canonical entry for the same LCID was already recorded above.
for name, tag, override in rows:
    if override in ('k0', 'kSAME') or name not in names:
        continue
    if override not in names:
        continue
    lcid = names[name]
    if lcid not in canonical and names[override] in canonical:
        canonical[lcid] = canonical[names[override]]

tags = {k: v for k, v in canonical.items() if 0 < k <= 0xFFFF}
print(f'{len(tags)} tags', file=sys.stderr)
for probe, want in [(0x0409, 'en-US'), (0x0407, 'de-DE'), (0x0C0A, 'es-ES'),
                    (0x0804, 'zh-CN'), (0x0411, 'ja-JP'), (0x081A, None)]:
    print(f'  0x{probe:04X} -> {tags.get(probe)} (expected {want})', file=sys.stderr)

# ---------------------------------------------------------------- emit C#

out = []
w = out.append
w('// <auto-generated>')
w("// Generated from LibreOffice's i18nlangtag tables:")
w('//   include/i18nlangtag/lang.h                the LANGUAGE_* identifiers and their values')
w('//   i18nlangtag/source/isolang/isolang.cxx    the tag each identifier maps to')
w('//')
w('// The three upstream tables are read in the order MsLangId::Conversion consults them --')
w('// BCP-47, then language+script+country, then language+country -- and an entry whose')
w('// mnOverride is set is skipped, because such an entry is not the canonical mapping for its')
w('// identifier. That is what makes this agree with LibreOffice rather than merely resemble it.')
w('//')
w('// Regenerate rather than edit: this is data, and a hand-made correction to one row would be')
w('// lost the next time it is rebuilt.')
w('// </auto-generated>')
w('')
w('namespace Paperless.Core.Globalization;')
w('')
w('public static partial class WindowsLanguages')
w('{')
w('    /// <summary>The identifier-to-tag table, in ascending identifier order.</summary>')
w('    /// <remarks>')
w('    /// A sorted array searched by bisection rather than a dictionary: it is built once, read')
w('    /// constantly and never changes, so the array costs a fraction of the memory and needs no hash')
w('    /// of a value that is already its own key.')
w('    /// </remarks>')
w('    private static readonly (ushort Identifier, string Tag)[] Table =')
w('    [')
for lcid in sorted(tags):
    w(f'        (0x{lcid:04X}, "{tags[lcid]}"),')
w('    ];')
w('}')

path = ROOT + 'dotnet/src/Paperless.Core/Globalization/WindowsLanguages.Table.cs'
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('written ' + path, file=sys.stderr)
