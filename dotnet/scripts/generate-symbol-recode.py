"""Generate the symbol-font recode tables from LibreOffice's own `fontcvt.cxx`.

A legacy symbol face — Wingdings, Symbol, Webdings, Monotype Sorts — addresses its glyphs by
byte position rather than by character, so a document states its bullet as `0xD8` and means
"the glyph in slot 0xD8 of Wingdings", not "Ø". LibreOffice moves that byte into the Private
Use Area (`(c & 0x00ff) | 0xf000`) and then, when the face itself is not installed, recodes it
through a per-face table into the code point the *same picture* occupies in OpenSymbol, which
ships with LibreOffice and is therefore always present.

Those tables are `unotools/source/misc/fontcvt.cxx`'s ten `sal_Unicode a…Tab[224]` arrays,
indexed by `slot - 0x20`. They are read rather than reimplemented for the same reason `VCL.xcu`
is: they encode what LibreOffice actually draws, and nothing else states the mapping.

Two traps, both met while writing this:

  * **A table hole is written as a bare `0`, not `0x0000`.** Parsing with a `0x[0-9a-f]+`
    regex silently drops those entries and shifts every index after them — `aWingDingsTab`
    then comes out at 223 entries and maps U+F0D8 to U+E49F instead of U+E49E. Both readings
    look entirely plausible and only one is right, so this script asserts the length is 224.
  * **`aStarBatsTab` and friends target StarSymbol, whose code points OpenSymbol only mostly
    shares.** The generator therefore records, per table, how many of its destinations the
    installed OpenSymbol actually has; see the summary it prints. It does *not* drop the
    misses, because that is a decision for the caller and depends on which font is resolved.
"""
import os
import re
import sys

# Derived from this script's own location rather than hardcoded, so running it from a git
# worktree regenerates that worktree's table and not some other checkout's.
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'unotools/source/misc/fontcvt.cxx')
OUT = os.path.join(ROOT, 'dotnet/src/Paperless.Text/Fonts/SymbolFontRecode.Tables.cs')

# `aStarSymbolRecodeTable`, fontcvt.cxx:1307-1329. Keys are already in the form
# `GetEnglishSearchFontName` produces, which is what `FontSubstitutions.Normalise` reproduces.
FACES = [
    ('starbats',         'aStarBatsTab'),
    ('starmath',         'aStarMathTab'),
    ('symbol',           'aAdobeSymbolTab'),
    ('standardsymbols',  'aAdobeSymbolTab'),
    ('standardsymbolsl', 'aAdobeSymbolTab'),
    ('monotypesorts',    'aMonotypeSortsTab'),
    ('zapfdingbats',     'aMonotypeSortsTab'),
    ('itczapfdingbats',  'aMonotypeSortsTab'),
    ('dingbats',         'aMonotypeSortsTab'),
    ('webdings',         'aWebDingsTab'),
    ('wingdings',        'aWingDingsTab'),
    ('wingdings2',       'aWingDings2Tab'),
    ('wingdings3',       'aWingDings3Tab'),
    ('mtextra',          'aMTExtraTab'),
]


def parse_tables(text):
    """Every `const sal_Unicode a…Tab[224] = { … };` in the file, as lists of 224 ints."""
    tables = {}
    for match in re.finditer(
            r'const sal_Unicode (a\w+Tab)\[224\]\s*=\s*\{(.*?)\n\};', text, re.S):
        name, body = match.group(1), match.group(2)
        body = re.sub(r'//[^\n]*', '', body)          # strip the `// F020` row markers
        values = []
        for token in body.split(','):
            token = token.strip()
            if not token:
                continue
            values.append(int(token, 16) if token.lower().startswith('0x') else int(token, 10))
        if len(values) != 224:
            raise SystemExit(
                f'{name}: parsed {len(values)} entries, expected 224. A hole is written as a '
                f'bare 0 and must be counted; see this script\'s docstring.')
        tables[name] = values
    return tables


text = open(SOURCE, encoding='utf-8', errors='replace').read()
tables = parse_tables(text)

for _, table in FACES:
    if table not in tables:
        raise SystemExit(f'{table} is named by aStarSymbolRecodeTable but not defined in {SOURCE}')

used = sorted({table for _, table in FACES})

def csharp_name(table):
    """`aWingDings2Tab` -> `WingDings2Table`, so the output reads as C# rather than as C++."""
    return re.sub(r'^a', '', re.sub(r'Tab$', 'Table', table))

lines = []
lines.append('// <auto-generated>')
lines.append('// Generated from LibreOffice\'s own symbol-font conversion tables:')
lines.append('//   unotools/source/misc/fontcvt.cxx, aStarSymbolRecodeTable and the a*Tab arrays')
lines.append('//')
lines.append('// Each table maps a legacy symbol face\'s slot to the code point the same picture')
lines.append('// occupies in OpenSymbol. Indexed by slot - 0x20; a zero is a hole in the mapping.')
lines.append('// Regenerate rather than edit: scripts/generate-symbol-recode.py.')
lines.append('// </auto-generated>')
lines.append('')
lines.append('namespace Paperless.Text.Fonts;')
lines.append('')
lines.append('public static partial class SymbolFontRecode')
lines.append('{')

# The arrays are emitted BEFORE the dictionary that references them. Static field
# initialisers run in textual order, so a dictionary declared first would capture nulls —
# and would do it silently, since nothing about a null entry looks wrong at the call site.
for table in used:
    values = tables[table]
    lines.append(f'    /// <summary><c>{table}</c>, 224 slots from 0x20 to 0xFF.</summary>')
    lines.append(f'    private static readonly ushort[] {csharp_name(table)} =')
    lines.append('    [')
    for row in range(0, 224, 8):
        chunk = ', '.join(f'0x{v:04X}' for v in values[row:row + 8])
        lines.append(f'        {chunk},')
    lines.append('    ];')
    lines.append('')

lines.append('    /// <summary>Normalised face name to the table that recodes its slots.</summary>')
lines.append('    private static readonly Dictionary<string, ushort[]> Tables =')
lines.append('        new(StringComparer.Ordinal)')
lines.append('        {')
for face, table in FACES:
    lines.append(f'            ["{face}"] = {csharp_name(table)},')
lines.append('        };')
lines.append('}')
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

print(f'wrote {OUT}')
print(f'  {len(FACES)} face names over {len(used)} tables')
for table in used:
    values = tables[table]
    holes = sum(1 for v in values if v == 0)
    print(f'  {table:<28} holes={holes}')
