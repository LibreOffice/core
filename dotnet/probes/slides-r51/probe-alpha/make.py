"""One-shape decks that vary ONE thing: whether the knocked-out PNG has an alpha channel.

Same pixels, same clrChange, same geometry. If LibreOffice knocks out the RGB one and not the
RGBA one, the alpha channel is the condition; if it knocks out both, it is not.
"""
import os, zipfile
from PIL import Image

W, H = 400, 120
def image(mode):
    im = Image.new("RGB", (W, H), (0xF4, 0xF4, 0xF4))
    for y in range(30, 90):
        for x in range(40, 200):
            im.putpixel((x, y), (0x11, 0x62, 0x70))
    return im.convert(mode)

