using System.Globalization;
using System.Text;
using Paperless.Text.Layout;
using Shouldly;

namespace Paperless.Text.Tests;

/// <summary>
/// Tests the UAX #14 line breaker.
/// </summary>
/// <remarks>
/// <para>
/// Two kinds of test. The differential one runs several thousand cases generated from an independent
/// implementation of the same specification over the same property data, which is evidence rather
/// than a restatement of this implementation's own logic. The named ones cover the rules that matter
/// most in practice, and — separately — the three places where LibreOffice deliberately differs from
/// plain UAX #14, where agreeing with the independent implementation would be *wrong*.
/// </para>
/// <para>
/// Unicode's own conformance file, <c>LineBreakTest.txt</c>, is the ideal third source and is not
/// reachable from this environment: the egress policy denies unicode.org. The differential cases are
/// generated by a script that can read the UCD directly when it is reachable.
/// </para>
/// </remarks>
public class LineBreakerTests
{
    private static readonly LineBreaker Breaker = LineBreaker.Instance;

    private static IReadOnlyList<int> Breaks(string text)
        => Breaker.FindBreakOpportunities(text);

    /// <summary>The text with a pipe at every permitted break, which is legible in a failure.</summary>
    private static string Marked(string text)
    {
        StringBuilder marked = new();
        HashSet<int> breaks = [.. Breaks(text)];
        for (int i = 0; i < text.Length; i++)
        {
            if (breaks.Contains(i)) marked.Append('|');
            marked.Append(text[i]);
        }
        return marked.Append('|').ToString();
    }

    [Fact]
    public void TheEndOfTextIsAlwaysABreakAndTheStartIsNever()
    {
        // LB2 and LB3. Every other rule is about the boundaries between characters, so these two
        // being wrong would show up as an off-by-one in every line rather than as a bad break.
        Breaks("word").ShouldBe([4]);
        Breaks("").ShouldBeEmpty();
        Breaks("x").ShouldBe([1]);
    }

    [Fact]
    public void ASpaceIsABreakOpportunityAfterItAndNotBeforeIt()
    {
        // LB7 then LB18: the break belongs after the space, so the space stays on the line it ends
        // rather than starting the next one.
        Marked("one two").ShouldBe("one |two|");
        Marked("one  two").ShouldBe("one  |two|");
    }

    [Fact]
    public void AHardBreakBreaksAndCarriageReturnLineFeedIsOnlyOne()
    {
        // LB4 and LB5. Treating CRLF as two breaks inserts a blank line into every Windows-written
        // paragraph.
        Marked("a\nb").ShouldBe("a\n|b|");
        Marked("a\r\nb").ShouldBe("a\r\n|b|");
        Breaks("a\r\nb").ShouldBe([3, 4]);
    }

    [Fact]
    public void NoBreakInsideAWordOrAroundAWordJoiner()
    {
        // LB28 and LB11.
        Marked("hello").ShouldBe("|hello|"[1..]);
        Marked("word⁠joiner").ShouldBe("word⁠joiner|");
    }

    [Fact]
    public void NoBreakEitherSideOfANonBreakingSpace()
    {
        // LB12: glue holds on both sides, which is the whole point of a non-breaking space.
        Marked("a b").ShouldBe("a b|");
        Marked("one two three").ShouldBe("one two |three|");
    }

    [Fact]
    public void BreakAfterAZeroWidthSpaceEvenAcrossTheSpacesFollowingIt()
    {
        // LB8. The zero-width space is how a producer says "a break is allowed here" in text that
        // otherwise offers none, so it has to survive trailing spaces.
        Marked("a​b").ShouldBe("a​|b|");
        // The break falls after the spaces, not before them: LB8 is "ZW SP* divide", so the
        // spaces belong to the line the zero-width space ends.
        Marked("a​  b").ShouldBe("a​  |b|");
    }

    [Fact]
    public void PunctuationStaysWithTheWordItFollows()
    {
        // LB13: no break before closing punctuation, an exclamation or a separator.
        Marked("Hello, world!").ShouldBe("Hello, |world!|");
        Marked("end.").ShouldBe("end.|");
    }

    [Fact]
    public void AnOpeningBracketKeepsWhatFollowsItHoweverManySpacesIntervene()
    {
        // LB14. This is the rule LB18 would defeat if the order were wrong: the space after the
        // bracket must not become a break.
        Marked("a (b)").ShouldBe("a |(b)|");
        Marked("a ( b)").ShouldBe("a |( b)|");
    }

    [Fact]
    public void ANumberIsNotBrokenApart()
    {
        // LB25. A number is a small grammar, not a character class, which is why a pair of classes
        // cannot decide it — whether a comma is inside a number or ends a clause depends on what
        // follows.
        Marked("1,234.56").ShouldBe("1,234.56|");
        Marked("$1,234.56").ShouldBe("$1,234.56|");
        Marked("50%").ShouldBe("50%|");

        // A comma that ends a clause is a break opportunity after it, unlike one inside a number.
        Marked("1, 2").ShouldBe("1, |2|");
    }

    [Fact]
    public void ALetterAndADigitStayTogether()
    {
        // LB23: "chapter7" and "7th" are single words.
        Marked("chapter7").ShouldBe("chapter7|");
        Marked("7th").ShouldBe("7th|");
    }

    [Fact]
    public void AHyphenatedWordBreaksAfterItsHyphen()
    {
        // LB21: no break *before* a hyphen, so the hyphen stays on the line it ends.
        Marked("hyphen-ated").ShouldBe("hyphen-|ated|");
    }

    [Fact]
    public void AnEmDashBreaksOnBothSidesButNotBetweenAPair()
    {
        // LB17 versus LB31: one dash offers a break on either side of it, and a pair holds
        // together in the middle — which is what stops two dashes being split apart.
        Marked("a—b").ShouldBe("a|—|b|");
        Marked("a——b").ShouldBe("a|——|b|");
    }

    [Fact]
    public void IdeographicTextBreaksBetweenCharacters()
    {
        // LB31 for CJK: every character is a break opportunity, which is what makes CJK lines fill.
        Marked("日本語").ShouldBe("日|本|語|");
    }

    [Fact]
    public void ACombiningMarkNeverSeparatesFromItsBase()
    {
        // LB9. A break between a letter and its accent would render the accent alone at the start of
        // a line.
        Marked("áb́").ShouldBe("áb́|");
        Breaks("é").ShouldBe([2]);
    }

    [Fact]
    public void AStandaloneCombiningMarkBehavesLikeALetter()
    {
        // LB10. A mark with no base is malformed text, and treating it as a mark would have it
        // attach to whatever precedes it across a space.
        Marked(" ́a").ShouldBe(" |́a|");
    }

    [Fact]
    public void ASurrogatePairIsOneCharacter()
    {
        // Every rule is about code points, so a break inside a pair would produce invalid UTF-16 —
        // and an emoji is the common case, not an exotic one.
        Breaks("a\U0001f600b").ShouldNotContain(2);
        Marked("a\U0001f600b").ShouldBe("a|\U0001f600|b|");
    }

    [Fact]
    public void AFlagStaysWholeAndTwoFlagsMayBeSeparated()
    {
        // LB30a: a flag is a pair of regional indicators, so the break goes between pairs and not
        // inside one. Counting them is the only way to know which boundary is which.
        string oneFlag = "\U0001f1e6\U0001f1e7";
        Breaks(oneFlag).ShouldBe([4]);

        string twoFlags = oneFlag + "\U0001f1e8\U0001f1e9";
        Breaks(twoFlags).ShouldBe([4, 8]);
    }

    [Fact]
    public void AnEmojiKeepsItsSkinToneModifier()
    {
        // LB30b.
        Breaks("\U0001f466\U0001f3fb").ShouldBe([4]);
    }

    [Fact]
    public void AZeroWidthJoinerHoldsAnEmojiSequenceTogether()
    {
        // LB8a. A joined sequence is one glyph, so a break inside it would render two.
        string family = "\U0001f468‍\U0001f469";
        Breaks(family).ShouldBe([family.Length]);
    }

    [Fact]
    public void AHangulSyllableIsNotBrokenApart()
    {
        // LB26: the jamo of one syllable belong together, though syllables break between themselves.
        Marked("가").ShouldBe("가|");
        Marked("가각").ShouldBe("가|각|");
    }

    // ------------------------------------------- LibreOffice's deliberate differences

    [Fact]
    public void AQuoteMayBreakBeforeAnOpeningBracket()
    {
        // LB15 disabled, LibreOffice issue i#83649. The customisation shows only across spaces:
        // adjacent, LB19's "no break after a quotation mark" still forbids it, and LB19 survives.
        // With a space between, LB18's break-after-a-space is what LB15 would have overridden.
        Marked("\"(a)").ShouldBe("\"(a)|");
        Marked("\" (a)").ShouldBe("\" |(a)|");
    }

    [Fact]
    public void ANumberRangeBreaksAfterItsHyphen()
    {
        // LibreOffice issue i#83229. Plain LB25 keeps "100-199" whole; LibreOffice adds a break
        // opportunity after the hyphen when a digit follows, so a wide range can wrap.
        Marked("100-199").ShouldBe("100-|199|");

        // Only between digits. A hyphen before a letter is an ordinary hyphen, and one before digits
        // with no digits before it is a negative number rather than a range — LB25 keeps that whole.
        Marked("100-x").ShouldBe("100-|x|");
        Marked("x-199").ShouldBe("x-199|");
    }

    [Fact]
    public void ALeadingHyphenKeepsTheLetterAfterIt()
    {
        // The rule LibreOffice's file notes as 20.9: the boundary between a hyphen and a following
        // letter is suppressed when there is already one before the hyphen. At the start of the text
        // there always is.
        Marked("-ated").ShouldBe("-ated|");
        Marked("‐ated").ShouldBe("‐ated|");

        // Not in the middle, where the hyphen has a word before it.
        Marked("a-b").ShouldBe("a-|b|");
    }

    [Fact]
    public void AHebrewHyphenHoldsWhateverFollowsIt()
    {
        // LB21a in the Unicode 15.0 form LibreOffice's ICU implements. Unicode 15.1 narrowed it to
        // "before a non-Hebrew letter", which would split this compound; LibreOffice keeps it whole,
        // and matching LibreOffice is the point.
        Marked("\u05E2\u05D1\u05E8\u05D9\u05EA-\u05D0\u05E0\u05D2\u05DC\u05D9\u05EA")
            .ShouldBe("\u05E2\u05D1\u05E8\u05D9\u05EA-\u05D0\u05E0\u05D2\u05DC\u05D9\u05EA|");

        // And before a non-Hebrew letter, where both revisions agree.
        Marked("\u05E2\u05D1-a").ShouldBe("\u05E2\u05D1-a|");
    }

    [Fact]
    public void SmallKanaMayNotStartALine()
    {
        // LibreOffice folds CJ into NS, which is CSS line-break: strict. Under normal breaking a
        // small kana would be ID and could begin a line.
        Marked("かぁ").ShouldBe("かぁ|");
    }

    [Fact]
    public void ThaiGetsNoIntraWordBreaksWithoutADictionary()
    {
        // LB1 resolves Complex_Context to AL, so Thai behaves as one long word. That is what any
        // implementation without a Thai dictionary produces, and it is the honest outcome: breaking
        // Thai in the wrong places would be worse than not breaking it.
        Marked("กขฃ").ShouldBe("กขฃ|");
    }

    // -------------------------------------------------------------- the property tables

    [Fact]
    public void ThePropertyTableCoversTheClassesTheRulesRead()
    {
        LineBreakProperties.RangeCount.ShouldBeGreaterThan(2000);

        LineBreakProperties.ClassOf('a').ShouldBe(LineBreakClass.AL);
        LineBreakProperties.ClassOf('5').ShouldBe(LineBreakClass.NU);
        LineBreakProperties.ClassOf(' ').ShouldBe(LineBreakClass.SP);
        LineBreakProperties.ClassOf(' ').ShouldBe(LineBreakClass.GL);
        LineBreakProperties.ClassOf('\r').ShouldBe(LineBreakClass.CR);
        LineBreakProperties.ClassOf('\n').ShouldBe(LineBreakClass.LF);
        LineBreakProperties.ClassOf('(').ShouldBe(LineBreakClass.OP);
        LineBreakProperties.ClassOf('日').ShouldBe(LineBreakClass.ID);
        LineBreakProperties.ClassOf('ぁ').ShouldBe(LineBreakClass.CJ);
        LineBreakProperties.ClassOf(0x1F1E6).ShouldBe(LineBreakClass.RI);
    }

    [Fact]
    public void AnUnassignedCodePointIsUnknownAndBehavesLikeALetter()
    {
        // Rather than stopping the walk: a document using a code point newer than these tables should
        // still lay out sensibly, which is what LB1 prescribes.
        LineBreakProperties.ClassOf(0x0870 - 1).ShouldBe(LineBreakClass.XX);
        LineBreakProperties.ClassOf(-1).ShouldBe(LineBreakClass.XX);
        LineBreakProperties.ClassOf(0x110000).ShouldBe(LineBreakClass.XX);
    }

    [Fact]
    public void WidthAndPictographicTablesAnswerWhatLb30AndLb30bAsk()
    {
        // LB30 applies only to narrow brackets, because a wide one is a CJK bracket and CJK text
        // breaks between characters.
        LineBreakProperties.IsWide('日').ShouldBeTrue();
        LineBreakProperties.IsWide('a').ShouldBeFalse();
        LineBreakProperties.IsWide('（').ShouldBeTrue();

        LineBreakProperties.IsExtendedPictographic(0x1F600).ShouldBeTrue();
        LineBreakProperties.IsExtendedPictographic('a').ShouldBeFalse();
    }

    // ------------------------------------------------------------------ differential

    [Fact]
    public void EveryDifferentialCaseAgreesWithAnIndependentImplementation()
    {
        List<string> failures = [];
        int cases = 0;

        foreach ((string text, int[] expected) in DifferentialCases())
        {
            cases++;
            IReadOnlyList<int> actual = Breaks(text);
            if (actual.SequenceEqual(expected)) continue;

            failures.Add(
                $"{Escape(text)}\n    expected [{string.Join(", ", expected)}]"
                + $"\n    actual   [{string.Join(", ", actual)}]");
        }

        cases.ShouldBeGreaterThan(3000, "the case file should not have been truncated");
        failures.ShouldBeEmpty(
            $"{failures.Count} of {cases} cases disagree with the reference implementation:\n"
            + string.Join("\n", failures.Take(25)));
    }

    private static IEnumerable<(string Text, int[] Breaks)> DifferentialCases()
    {
        string path = Path.Combine(AppContext.BaseDirectory, "line-break-cases.txt");
        File.Exists(path).ShouldBeTrue($"the generated case file is missing from {path}");

        foreach (string line in File.ReadLines(path))
        {
            if (line.Length == 0 || line[0] == '#') continue;

            string[] parts = line.Split('\t');
            if (parts.Length != 2) continue;

            yield return (
                Unescape(parts[0]),
                [.. parts[1].Split(' ', StringSplitOptions.RemoveEmptyEntries)
                            .Select(o => int.Parse(o, CultureInfo.InvariantCulture))]);
        }
    }

    private static string Unescape(string escaped)
    {
        StringBuilder text = new(escaped.Length / 6);
        for (int i = 0; i + 6 <= escaped.Length; i += 6)
        {
            text.Append((char)ushort.Parse(
                escaped.AsSpan(i + 2, 4), NumberStyles.HexNumber, CultureInfo.InvariantCulture));
        }
        return text.ToString();
    }

    private static string Escape(string text)
    {
        StringBuilder escaped = new();
        foreach (char character in text)
        {
            escaped.Append(character is >= ' ' and <= '~'
                ? character.ToString()
                : $"\\u{(int)character:X4}");
        }
        return escaped.ToString();
    }
}
