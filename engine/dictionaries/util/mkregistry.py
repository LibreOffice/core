# Builds the configuration layer that tells the linguistic services where the
# bundled dictionaries are.
#
# Usage: mkregistry.py <srcdir> <installed-dir> <output.xcd> <name>=<srcdir> ...
#
#   mkregistry.py . share/extensions out.xcd dict-ru=dictionaries/ru_RU ...
#
# Each dictionary carries a dictionaries.xcu, and a few carry a Linguistic.xcu
# as well. They are written to be registered as extensions, which resolves
# "%origin%" to wherever the extension was unpacked. Nothing installs them as
# extensions, so resolve it here instead, against the directory they are
# installed in, and merge the lot into one layer the configuration reads at
# startup.

import argparse
import os
import re
import sys

HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by dictionaries/util/mkregistry.py; do not edit. -->
<oor:data xmlns:oor="http://openoffice.org/2001/registry"
          xmlns:xs="http://www.w3.org/2001/XMLSchema"
          xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
<!-- The schema for Linguistic is in main, and a layer is only read once
     what it adds to has been declared. -->
<dependency file="main"/>
"""

FOOTER = "</oor:data>\n"

# The parts of an .xcu that must not be repeated inside the wrapper.
DECLARATION = re.compile(r"<\?xml[^>]*\?>\s*")
DOCTYPE = re.compile(r"<!DOCTYPE[^>]*>\s*")
COMMENT = re.compile(r"<!--.*?-->\s*", re.S)


def fragment(path, origin):
    """One .xcu as a component-data element, with %origin% resolved."""
    text = open(path, encoding="utf-8").read()
    text = DECLARATION.sub("", text)
    text = DOCTYPE.sub("", text)
    text = COMMENT.sub("", text)
    text = text.strip()
    if not text.startswith("<oor:component-data"):
        sys.exit("mkregistry: %s is not component-data" % path)
    if "%origin%" in text and origin is None:
        sys.exit("mkregistry: %s uses %%origin%% but no location is known" % path)
    return text.replace("%origin%", origin) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Build the bundled dictionary registry")
    parser.add_argument("srcdir", help="the source tree root")
    parser.add_argument("installdir", help="where the dictionaries are installed, under the brand directory")
    parser.add_argument("output", help="the .xcd to write")
    parser.add_argument("dictionaries", nargs="*", metavar="name=srcdir",
                        help="a dictionary's installed name and its directory in the source tree")
    args = parser.parse_args()

    parts = []
    count = 0
    for entry in args.dictionaries:
        if not entry:
            continue
        name, _, where = entry.partition("=")
        if not name or not where:
            sys.exit("mkregistry: cannot read %r as name=srcdir" % entry)
        # SvtLinguConfig resolves a location with getExpandedUri, which only
        # expands a vnd.sun.star.expand: URI and hands anything else back
        # unchanged, to be dropped for not being a file URL.
        origin = "vnd.sun.star.expand:$BRAND_BASE_DIR/%s/%s" % (args.installdir, name)
        found = False
        for xcu in ("dictionaries.xcu", "Linguistic.xcu"):
            path = os.path.join(args.srcdir, where, xcu)
            if os.path.exists(path):
                parts.append(fragment(path, origin))
                found = True
        if not found:
            sys.exit("mkregistry: %s has no dictionaries.xcu" % where)
        count += 1

    with open(args.output, "w", encoding="utf-8") as out:
        out.write(HEADER)
        for part in parts:
            out.write(part)
        out.write(FOOTER)

    sys.stderr.write("mkregistry: %d dictionaries, %d fragments\n" % (count, len(parts)))


if __name__ == "__main__":
    main()
