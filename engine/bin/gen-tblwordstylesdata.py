def derive_color(base_hex, tint=None, shade=None):
    r, g, b = (int(base_hex[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if tint is not None:
        t = tint / 255.0
        l = l * t + (1 - t)
    if shade is not None:
        l = l * (shade / 255.0)
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    # Word truncates; the epsilon keeps an exact value from flooring one step low.
    return '%02X%02X%02X' % tuple(int(c * 255 + 1e-6) for c in (r, g, b))


def recolor_styles(xml, palette):
    element = re.compile(r'<w:(\w+)\b([^>]*?)/>')

    def attr(attrs, name):
        m = re.search(r'\bw:%s="([^"]*)"' % name, attrs)
        return m.group(1) if m else None

    def set_attr(attrs, name, value):
        return re.sub(r'(\bw:%s=")[^"]*(")' % name, r'\g<1>' + value + r'\g<2>', attrs)

    def hex_or_none(value):
        return int(value, 16) if value else None

    def fix(m):
        tag, attrs = m.group(1), m.group(2)
        theme_color = attr(attrs, 'themeColor')
        if theme_color in palette:
            target = 'val' if tag == 'color' else 'color'
            if attr(attrs, target) not in (None, 'auto'):
                attrs = set_attr(attrs, target, derive_color(
                    palette[theme_color], hex_or_none(attr(attrs, 'themeTint')),
                    hex_or_none(attr(attrs, 'themeShade'))))
        theme_fill = attr(attrs, 'themeFill')
        if theme_fill in palette and attr(attrs, 'fill') not in (None, 'auto'):
            attrs = set_attr(attrs, 'fill', derive_color(
                palette[theme_fill], hex_or_none(attr(attrs, 'themeFillTint')),
                hex_or_none(attr(attrs, 'themeFillShade'))))
        return '<w:%s%s/>' % (tag, attrs)

    return element.sub(fix, xml)


def recolor_theme(xml, palette):
    for name, tag in THEME_CLR_SCHEME_TAGS.items():
        xml, n = re.subn(
            r'(<a:%s>\s*)<a:srgbClr val="[0-9A-Fa-f]{6}"/>(\s*</a:%s>)' % (tag, tag),
            r'\g<1><a:srgbClr val="%s"/>\g<2>' % palette[name], xml)
        if n != 1:
            raise SystemExit('theme1.xml: expected one <a:%s> srgbClr, found %d' % (tag, n))
    return xml


def table_style_ids(styles_xml):
    ids = []
    for m in re.finditer(r'<w:style [^>]*>', styles_xml):
        tag = m.group(0)
        if 'w:type="table"' not in tag or 'w:customStyle="1"' in tag:
            continue
        style_id = re.search(r'w:styleId="([^"]*)"', tag).group(1)
        if style_id != 'TableNormal':
            ids.append(style_id)
    return sorted(set(ids))


def build_document(style_ids):
    tables = []
    for style_id in style_ids:
        tables.append(
            '<w:tbl><w:tblPr><w:tblStyle w:val="%s"/><w:tblW w:w="0" w:type="auto"/>'
            '<w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="1" '
            'w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr>'
            '<w:tblGrid><w:gridCol w:w="1000"/></w:tblGrid>'
            '<w:tr><w:tc><w:tcPr><w:tcW w:w="1000" w:type="dxa"/></w:tcPr><w:p/></w:tc></w:tr>'
            '</w:tbl><w:p/>' % style_id)
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        '<w:body>' + ''.join(tables) +
        '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/></w:sectPr></w:body></w:document>')


def extract(docx_path):
    with zipfile.ZipFile(docx_path) as z:
        styles = z.read('word/styles.xml').decode('utf-8')
        theme = z.read('word/theme/theme1.xml').decode('utf-8')
    styles = recolor_styles(styles, STOCK_THEME)
    theme = recolor_theme(theme, STOCK_THEME)
    ids = table_style_ids(styles)
    os.makedirs(XML_DIR, exist_ok=True)
    for name, content in (('styles.xml', styles), ('theme1.xml', theme),
                          ('document.xml', build_document(ids))):
        with open(os.path.join(XML_DIR, name), 'w') as f:
            f.write(content)
    print('extracted %d table styles from %s' % (len(ids), docx_path))


def write_header():
    with open(HEADER, 'w') as out:
        out.write(HEADER_TEXT)
        for name, variable in PARTS:
            with open(os.path.join(XML_DIR, name)) as f:
                content = f.read()
            if ')%s"' % DELIMITER in content:
                raise SystemExit('%s contains the raw string delimiter' % name)
            # A char array plus a two-argument string_view: constructing the view from the
            # array alone would run char_traits::length as a constexpr loop over the whole
            # text, and GCC caps such loops well below the size of styles.xml.
            array = 'g_a' + variable[3:]
            out.write('inline constexpr char %s[] = R"%s(%s)%s";\n'
                      % (array, DELIMITER, content, DELIMITER))
            out.write('inline constexpr std::string_view %s(%s, sizeof(%s) - 1);\n\n'
                      % (variable, array, array))
        out.write(FOOTER_TEXT)
    print('wrote', os.path.relpath(HEADER, ROOT))


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--extract':
        extract(sys.argv[2])
    elif len(sys.argv) != 1:
        raise SystemExit(__doc__ or 'usage: gen-tblwordstylesdata.py [--extract file.docx]')
    write_header()

