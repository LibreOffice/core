# Those parts form a minimal DOCX package holding Word's built-in table style catalog. To
# re-extract them from a Word-authored document (one whose styles.xml carries the built-in
# table styles, as any document saved by Word with a styled table does), pass it:
#
#     bin/gen-tblwordstylesdata.py --extract some.docx
#
# Extraction rewrites every literal color in styles.xml from the stock Office theme palette,
# because the DOCX import filter applies the literal w:fill / w:color values and keeps the
# w:themeColor / w:themeFill references for round-trip only. Word derives a literal from its
# theme color in HSL space: a tint moves the luminance towards white as L' = L * t + (1 - t),
# a shade towards black as L' = L * s, with the result truncated to whole channel values. That
# reproduces the values Word writes exactly for all but a few, which come out one channel step
# apart.

