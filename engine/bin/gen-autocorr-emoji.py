# Generate the emoji AutoCorrect replacements from
# extras/source/autocorr/emoji/emoji.txt.
#
# The shortcodes are the international GitHub/Slack names, so they are written
# to the "und" (undetermined) replacement list, which SvxAutoCorrect consults
# for every document language.  See extras/source/autocorr/emoji/README.md.
#
# Usage:
#   ./bin/gen-autocorr-emoji.py              regenerate lang/und/DocumentList.xml
#   ./bin/gen-autocorr-emoji.py --check      fail if it is out of date
#   ./bin/gen-autocorr-emoji.py --strip-localized
#                                            remove the emoji replacements from
#                                            the per language lists, where they
#                                            used to live under translated names

import argparse
import os
import re
import sys
from xml.sax.saxutils import quoteattr

SRCDIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(SRCDIR, 'extras/source/autocorr/emoji/emoji.txt')
LANGDIR = os.path.join(SRCDIR, 'extras/source/autocorr/lang')
NS = 'http://openoffice.org/2001/block-list'
BLOCK = '  <block-list:block block-list:abbreviated-name={} block-list:name={}/>\n'


def read_data():
    """emoji.txt -> [(shortcode, character)], most specific checks included."""
    pairs = []
    seen = {}
    with open(DATA, encoding='utf-8') as f:
        for lineno, line in enumerate(f, 1):
            if line.startswith('#') or not line.strip():
                continue
            fields = line.rstrip('\n').split('\t')
            if len(fields) != 4:
                sys.exit('%s:%d: expected 4 tab separated fields' % (DATA, lineno))
            codepoints, char, shortcodes, _name = fields
            expected = ''.join(chr(int(cp, 16)) for cp in codepoints.split())
            if expected != char:
                sys.exit('%s:%d: %s is not U+%s' % (DATA, lineno, char, codepoints))
            for code in [s.strip() for s in shortcodes.split(',')]:
                if not code:
                    sys.exit('%s:%d: empty shortcode' % (DATA, lineno))
                if ':' in code:
                    sys.exit('%s:%d: shortcode %r must not contain a colon'
                             % (DATA, lineno, code))
                if code in seen and seen[code] != char:
                    sys.exit('%s:%d: shortcode %r is already taken by %s'
                             % (DATA, lineno, code, seen[code]))
                seen[code] = char
                pairs.append((code, char))
    return pairs


def document_list(pairs):
    out = ['<?xml version="1.0" encoding="utf-8"?>\n',
           '<!-- generated by bin/gen-autocorr-emoji.py, do not edit -->\n',
           '<block-list:block-list xmlns:block-list="%s">\n' % NS]
    for code, char in sorted(pairs):
        out.append(BLOCK.format(quoteattr(':%s:' % code), quoteattr(char)))
    out.append('</block-list:block-list>\n')
    return ''.join(out)


def strip_localized():
    """Drop the :shortcode: blocks that used to carry the translated names.

    Every colon delimited replacement belongs to this feature - the convention
    was introduced for it in 2015 - and is owned by the shared "und" list now.
    """
    pattern = re.compile(
        r'[ \t]*<block-list:block block-list:abbreviated-name="(:[^"]+:)"'
        r'\s+block-list:name="([^"]*)"\s*(?:/>|></block-list:block>)\n')
    for lang in sorted(os.listdir(LANGDIR)):
        path = os.path.join(LANGDIR, lang, 'DocumentList.xml')
        if lang == 'und' or not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as f:
            text = f.read()
        new, removed = pattern.subn('', text)
        if removed:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(new)
        print('%-12s %5d removed' % (lang, removed))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='only report whether the generated file is current')
    parser.add_argument('--strip-localized', action='store_true',
                        help='remove the emoji blocks from the per language lists')
    args = parser.parse_args()

    pairs = read_data()
    target = os.path.join(LANGDIR, 'und', 'DocumentList.xml')
    generated = document_list(pairs)

    if args.check:
        current = open(target, encoding='utf-8').read() if os.path.exists(target) else ''
        if current != generated:
            sys.exit('%s is out of date, run bin/gen-autocorr-emoji.py' % target)
        print('%s is up to date (%d shortcodes)' % (target, len(pairs)))
        return

    if args.strip_localized:
        strip_localized()
        return

    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, 'w', encoding='utf-8') as f:
        f.write(generated)
    print('%s: %d shortcodes for %d characters'
          % (target, len(pairs), len({c for _, c in pairs})))


if __name__ == '__main__':
    main()
